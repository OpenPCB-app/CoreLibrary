const KICAD_LICENSE = "CC-BY-SA-4.0+KiCad-Libraries-Exception";
const INCOMPATIBLE_KICAD_LICENSES = new Set(["CC-BY-4.0", "CC0-1.0"]);
// Non-KiCad asset sources (symbols/STEP authored or generated by OpenPCB, or
// redistributable manufacturer 3D). These fill the same full provenance record
// as KiCad-derived assets, but carry their own license rules (see checkProvenance).
const GENERATED_LICENSE = "CC-BY-SA-4.0";
const COMPATIBLE_GENERATED_LICENSES = new Set([
  GENERATED_LICENSE,
  KICAD_LICENSE,
]);
function fail(file: string, message: string) {
  issues.push({ file: displayPath(file), message });
}

function warn(file: string, message: string) {
  const issue = { file: displayPath(file), message };
  if (STRICT) issues.push(issue);
  else warnings.push(issue);
}

function warnDisplay(file: string, message: string) {
  const issue = { file, message };
  if (STRICT) issues.push(issue);
  else warnings.push(issue);
}

// Advisory note: always informational, never escalates to a failure under --strict.
function note(file: string, message: string) {
  warnings.push({ file: displayPath(file), message });
}

// G6–G12 live in tools/gates/*; each finding carries its own severity.
// `fail` is always fatal, `warn` is fatal under --strict, `note` never is.
function reportFindings(file: string, findings: GateFinding[]): void {
  for (const f of findings) {
    const message = `${f.gate}: ${f.message}`;
    if (f.severity === "fail") fail(file, message);
    else if (f.severity === "warn") warn(file, message);
    else note(file, message);
  }
}

function isHttpUri(value: string): boolean {
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}

function displayPath(absPath: string): string {
  return path.relative(LIBRARY_ROOT, absPath).split(path.sep).join("/");
}

function hasValue(value: unknown): boolean {
  if (typeof value === "string") return value.trim().length > 0;
  if (Array.isArray(value)) return true;
  return value !== undefined && value !== null;
}

function checkProvenance(file: string, provenance: Provenance) {
  const source = provenance.source;

  // Non-KiCad carve-out: OpenPCB-authored/generated assets and redistributable
  // manufacturer 3D. Same full provenance record is required; only the license
  // rule differs. (Truly-unknown sources still fall through untouched below.)
  if (source === "openpcb-generated" || source === "manufacturer") {
    for (const field of REQUIRED_KICAD_PROVENANCE_FIELDS) {
      if (!hasValue(provenance[field]))
        fail(file, `missing provenance field for ${source} asset: ${field}`);
    }
    if (
      Array.isArray(provenance.attribution) &&
      provenance.attribution.length === 0
    )
      warn(file, `${source} asset has empty attribution`);

    if (source === "openpcb-generated") {
      if (!COMPATIBLE_GENERATED_LICENSES.has(provenance.license ?? ""))
        fail(
          file,
          `openpcb-generated asset must be ${GENERATED_LICENSE} (or the KiCad exception), got: ${provenance.license ?? "<missing>"}`,
        );
    } else {
      if (!hasValue(provenance.license))
        fail(file, "manufacturer asset must declare a license");
      else if (INCOMPATIBLE_KICAD_LICENSES.has(provenance.license ?? ""))
        fail(
          file,
          `manufacturer asset uses a copyleft-incompatible license: ${provenance.license}`,
        );
      // Third-party-licensed but redistributable — surface for aggregate-license review.
      note(
        file,
        `manufacturer-sourced asset under third-party license '${provenance.license ?? "<missing>"}' — verify redistribution rights`,
      );
    }
    return;
  }

  if (source !== "kicad-derived") return;

  for (const field of REQUIRED_KICAD_PROVENANCE_FIELDS) {
    if (!hasValue(provenance[field]))
      fail(file, `missing KiCad provenance field: ${field}`);
  }

  if (provenance.license !== KICAD_LICENSE) {
    const reason = INCOMPATIBLE_KICAD_LICENSES.has(provenance.license ?? "")
      ? "weak conflicting license"
      : "non-CC-BY-SA compatible license";
    fail(
      file,
      `KiCad-derived asset uses ${reason}: ${provenance.license ?? "<missing>"}`,
    );
  }

  if (
    Array.isArray(provenance.attribution) &&
    provenance.attribution.length === 0
  ) {
    warn(file, "KiCad-derived asset has empty attribution");
  }
}

